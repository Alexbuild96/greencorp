"""Категории вещей. Каждая добавляет к промптам знания предметной области.

Чтобы добавить категорию, достаточно новой записи в CATEGORIES.
"""
from dataclasses import dataclass, field


@dataclass(frozen=True)
class Category:
    key: str
    name: str
    appraise_hint: str
    listing_hint: str
    seller_checklist: list[str] = field(default_factory=list)


FILM_CAMERAS = Category(
    key="film_cameras",
    name="Плёночные камеры и объективы",
    appraise_hint="""Категория: винтажные и плёночные фотоаппараты, объективы, аксессуары.
- Определяй марку и модель по надписям на корпусе, шильдику, байонету. Отличай похожие модификации (например, версии с разным видоискателем или байонетом) — от них сильно зависит цена.
- Для объективов важны: фокусное расстояние, светосила, байонет, версия. Байонет определяет, для какой системы объектив подходит.
- Смотри на состояние: потёртости, вмятины на корпусе, следы коррозии в батарейном отсеке, состояние кожзама, видимый грибок или царапины на линзах.
- Редкими считай ограниченные серии, ранние версии, необычные цвета, комплекты с оригинальной коробкой.
- Возможные подделки и «франкенштейны»: корпуса с чужими шильдиками, объективы не от этой модели. Добавляй предупреждение, если что-то выглядит несоответствующим.
- Работоспособность по фото проверить нельзя: не утверждай, что затвор и экспонометр работают, а вынеси это в questions_for_seller.""",
    listing_hint="""Название: марка, модель, для объектива — фокусное/светосила/байонет.
В описании честно перечисли комплектацию и известные дефекты. Если работоспособность не проверена — так и напиши.
Не пиши «состояние идеальное» без оснований.""",
    seller_checklist=[
        "Срабатывает ли затвор на всех выдержках, включая длинные?",
        "Работает ли экспонометр (нужна ли батарейка, какая)?",
        "Есть ли грибок, пыль, царапины или помутнение на линзах объектива?",
        "Плавно ли ходят кольца фокусировки и диафрагмы?",
        "Не подтекали ли батарейки, есть ли коррозия в отсеке?",
        "Целы ли светоизоляционные уплотнители (не липкие ли)?",
        "Что в комплекте: крышки, ремень, чехол, коробка, инструкция?",
        "Серийный номер (для определения года и подлинности)?",
    ],
)

CATEGORIES: dict[str, Category] = {c.key: c for c in [FILM_CAMERAS]}
DEFAULT_CATEGORY = FILM_CAMERAS.key


def get_category(key: str | None) -> Category:
    try:
        return CATEGORIES[key or DEFAULT_CATEGORY]
    except KeyError:
        raise ValueError(f"Неизвестная категория: {key}") from None
